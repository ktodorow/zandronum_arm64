def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="generated PK3 path; keep outside version control")
    parser.add_argument("--acc", type=Path, required=True, help="official ACC executable")
    parser.add_argument("--acc-include", type=Path, action="append", default=[], help="ACC include directory containing zcommon.acs")
    args = parser.parse_args()
    acc = args.acc.expanduser().resolve()
    if not acc.is_file():
        parser.error(f"ACC executable missing: {acc}")
    includes = [path.expanduser().resolve() for path in args.acc_include] or [acc.parent]
    if not any((path / "zcommon.acs").is_file() for path in includes):
        parser.error("--acc-include must contain official zcommon.acs")
    content, manifest = assets(acc, includes)
    output = args.output.expanduser().resolve()
    if output.exists():
        parser.error("output already exists; preserve prior qualified fixtures and use a new path")
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in sorted(content.items()):
            entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.create_system = 3
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, data)
    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    print(json.dumps(dict(output=str(output), sha256=digest, bytes=output.stat().st_size,
                          maps=[item["map"] for item in manifest["maps"]]), indent=2))


if __name__ == "__main__":
    main()
