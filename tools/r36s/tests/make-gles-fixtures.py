def packed(fmt, *values):
    return struct.pack("<" + fmt, *values)


def png(width, height, pixel, offset=None):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))
    raw = b"".join(b"\0" + bytes(c for x in range(width) for c in pixel(x, y))
                   for y in range(height))
    grab = chunk(b"grAb", struct.pack(">ii", *offset)) if offset is not None else b""
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)) + grab
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def wad(lumps):
    offset = 12
    data, directory = [], []
    for name, content in lumps:
        data.append(content)
        directory.append(packed("II8s", offset, len(content), name.encode().ljust(8, b"\0")))
        offset += len(content)
    return b"PWAD" + packed("II", len(lumps), offset) + b"".join(data + directory)


def block(kind, values):
    def literal(value):
        if isinstance(value, bool):
            return str(value).lower()
        if isinstance(value, str):
            return json.dumps(value)
        return str(value)
    return kind + " { " + " ".join(f"{key} = {literal(value)};" for key, value in values.items()) + " }\n"


class Map:
    def __init__(self):
        self.vertices, self.sectors, self.sides, self.lines, self.things = [], [], [], [], []
        self.vertex_ids, self.edges = {}, {}

    def vertex(self, xy):
        if xy not in self.vertex_ids:
            self.vertex_ids[xy] = len(self.vertices)
            self.vertices.append(dict(x=float(xy[0]), y=float(xy[1])))
        return self.vertex_ids[xy]

    def rectangle(self, x, y, width, height, **properties):
        sector = len(self.sectors)
        values = dict(heightfloor=0, heightceiling=192, texturefloor="GCFLOOR",
                      textureceiling="GCCEIL", lightlevel=160)
        values.update(properties)
        self.sectors.append(values)
        corners = [(x, y), (x, y + height), (x + width, y + height), (x + width, y)]
        edges = []
        for start, end in zip(corners, corners[1:] + corners[:1]):
            side = len(self.sides)
            self.sides.append(dict(sector=sector, texturetop="GCBRICK", texturebottom="GCBRICK", texturemiddle="GCBRICK"))
            if (end, start) in self.edges:
                line_id = self.edges[(end, start)]
                line = self.lines[line_id]
                line.update(sideback=side, twosided=True, blocking=False)
                self.sides[line["sidefront"]]["texturemiddle"] = "-"
                self.sides[side]["texturemiddle"] = "-"
            else:
                line_id = len(self.lines)
                self.edges[(start, end)] = line_id
                self.lines.append(dict(v1=self.vertex(start), v2=self.vertex(end), sidefront=side, blocking=True))
            edges.append(line_id)
        return sector, edges

    def room(self, **properties):
        sectors = {}
        for y in range(4):
            for x in range(4):
                sector, _ = self.rectangle(x * 128, y * 128, 128, 128, **properties)
                sectors[x, y] = sector
        return sectors

    def thing(self, kind, x, y, z=0, angle=90, tid=0, **properties):
        self.things.append(dict(type=kind, x=float(x), y=float(y), height=float(z), angle=angle,
                                id=tid, skill1=True, skill2=True, skill3=True, skill4=True,
                                skill5=True, single=True, dm=True, coop=True, **properties))

    def edge(self, start, end):
        return self.edges.get((start, end), self.edges.get((end, start)))

    def special(self, line_id, number, *args):
        self.lines[line_id]["special"] = number
        self.lines[line_id].update({f"arg{i}": value for i, value in enumerate(args)})

    def text(self):
        return ('namespace = "ZDoom";\n' + "".join(block(kind, item) for kind, values in
                (("vertex", self.vertices), ("sector", self.sectors), ("sidedef", self.sides),
                 ("linedef", self.lines), ("thing", self.things)) for item in values)).encode()


CUBE = [(-16, -16, 0), (16, -16, 0), (16, 16, 0), (-16, 16, 0),
        (-16, -16, 40), (16, -16, 40), (16, 16, 40), (-16, 16, 40)]
FACES = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
         (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
UV = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)] * 2


def md2():
    # MD2 indexed positions plus GL triangle commands, two animation frames.
    skins = b"skin.png".ljust(64, b"\0")
    coords = b"".join(packed("hh", int(u * 63), int(v * 63)) for u, v in UV)
    triangles = b"".join(packed("6H", *face, *face) for face in FACES)
    frames = b""
    for frame in range(2):
        positions = [(x + 16, y + 16, z + (12 * frame if z else 0)) for x, y, z in CUBE]
        frames += packed("6f16s", 1, 1, 1, -16, -16, 0, f"frame{frame}".encode())
        frames += b"".join(packed("4B", x, y, z, 0) for x, y, z in positions)
    commands = b"".join(packed("i", 3) + b"".join(packed("ffi", *UV[i], i) for i in face) for face in FACES) + packed("i", 0)
    offsets = [68]
    for data in (skins, coords, triangles, frames, commands):
        offsets.append(offsets[-1] + len(data))
    header = packed("17i", 844121161, 8, 64, 64, 40 + len(CUBE) * 4, 1, len(CUBE), len(UV), len(FACES),
                    len(commands) // 4, 2, *offsets)
    return header + skins + coords + triangles + frames + commands


def md3():
    frames = b"".join(packed("10f16s", -16, -16, 0, 16, 16, 52, 0, 0, 26, 40, f"frame{i}".encode()) for i in range(2))
    triangles = b"".join(packed("3i", *face) for face in FACES)
    shaders = packed("64si", b"skin.png", 0)
    coords = b"".join(packed("2f", *uv) for uv in UV)
    vertices = b"".join(packed("4h", x * 64, y * 64, (z + (12 * frame if z else 0)) * 64, 0)
                        for frame in range(2) for x, y, z in CUBE)
    offsets = [108]
    for data in (triangles, shaders, coords, vertices):
        offsets.append(offsets[-1] + len(data))
    surface = packed("4s64s10i", b"IDP3", b"original_cube", 0, 2, 1, len(CUBE), len(FACES), *offsets)
    surface += triangles + shaders + coords + vertices
    return packed("4si64s9i", b"IDP3", 15, b"original_fixture", 0, 2, 0, 1, 1, 108,
                  108 + len(frames), 108 + len(frames), 108 + len(frames) + len(surface)) + frames + surface


def kvx():
    # One solid 12x12x24 mip; only exterior side faces, plus top/bottom.
    sx, sy, sz = 12, 12, 24
    slab_size = 3 + sz
    offset_size = (sx + 1) * 4 + sx * (sy + 1) * 2
    xoffset = b"".join(packed("i", offset_size + x * sy * slab_size) for x in range(sx + 1))
    xyoffset = b"".join(packed("h", y * slab_size) for _ in range(sx) for y in range(sy + 1))
    slabs = b"".join(bytes([0, sz, 16 | 32 | (1 if x == 0 else 0) | (2 if x == sx - 1 else 0)
                            | (4 if y == 0 else 0) | (8 if y == sy - 1 else 0)])
                     + bytes(32 + (z // 4 % 3) * 64 for z in range(sz))
                     for x in range(sx) for y in range(sy))
    payload = packed("6i", sx, sy, sz, sx * 128, sy * 128, sz * 256) + xoffset + xyoffset + slabs
    # KVX channels are six-bit. V1's modulo64 palette accidentally gave all
    # used indices (32/96/160) the same gray; explicit entries make bands useful.
    diagnostic = {32: (63, 8, 4), 96: (4, 63, 8), 160: (8, 4, 63)}
    palette = bytes(c for i in range(256) for c in diagnostic.get(i, ((i * 5) % 64, (i * 3) % 64, (i * 7) % 64)))
    return packed("i", len(payload)) + payload + palette


def acs_source(camera=False, sky=False):
    # Camera 9002 makes recorded test viewpoint independent of player view bob.
    # Keep ordinary/camera source byte-identical to V1, notably GLTEST05.
    pitch = '    SetActorPitch(9002, -0.09375);\n' if sky else ''
    pitch_log = '    Log(s:"GLES-FIXTURE SKY PITCH ", d:GetActorPitch(9002));\n' if sky else ''
    return ('''#include "zcommon.acs"
script 1 OPEN
{
    Delay(1);
''' + ('    SetCameraToTexture(9001, "GCMON", 90);\n' if camera else '') + '''}
script 4 ENTER
{
    Delay(1);
''' + pitch + '''    ChangeCamera(9002, 0, 1);
''' + pitch_log + '''\
    Log(s:"GLES-FIXTURE READY");
}
script 2 (void) { ''' + ('SetActorPitch(9002, -0.09375); ' if sky else '') + '''ChangeCamera(9002, 0, 1); }
script 3 (void) { ChangeCamera(0, 0, 0); }
''' + ('script 5 (void) { SetActorPitch(9002, 0); ChangeCamera(9002, 0, 1); }\n' if sky else ''))


def compile_acs(source, acc, includes):
    with tempfile.TemporaryDirectory(prefix="gles-fixture-acs-") as directory:
        path = Path(directory)
        (path / "fixture.acs").write_text(source)
        command = [str(acc)]
        for include in includes:
            command += ["-i", str(include)]
        command += [str(path / "fixture.acs"), str(path / "behavior.o")]
        result = subprocess.run(command, cwd=path, capture_output=True, text=True)
        if result.returncode or not (path / "behavior.o").is_file():
            raise RuntimeError("ACC failed:\n" + result.stdout + result.stderr)
        return (path / "behavior.o").read_bytes()


